#!/usr/bin/env bash
# Generate the local .env used by docker-compose.
#
# No secret is committed to this repository. This script creates a .env with a
# freshly generated JWT signing key and mock-server admin token, so a clean
# extraction can be brought up without a hard-coded credential ever existing in
# version control. Run it once from the project root:
#
#     ./scripts/bootstrap_env.sh
#     docker compose up -d --build
#
# Re-running it will not overwrite an existing .env unless --force is given.

set -euo pipefail

cd "$(dirname "$0")/.."

FORCE=0
[[ "${1:-}" == "--force" ]] && FORCE=1

if [[ -f .env && $FORCE -eq 0 ]]; then
  echo ".env already exists; leaving it alone (use --force to regenerate)."
  exit 0
fi

gen() { head -c 48 /dev/urandom | base64 | tr -d '/+=' | head -c 48; }

cat > .env <<EOF
# Generated by scripts/bootstrap_env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Local laboratory credentials. Do not commit this file.

JWT_SECRET=$(gen)
MOCK_ADMIN_TOKEN=$(gen)

# Acknowledge that this is the single-host experimental stack described in
# docker-compose.yml. Set to 0 and supply hardened settings before using any
# part of this system outside an isolated lab.
MCP_GATEWAY_LAB_MODE=1

# Refuse to serve tool calls unless a tool-schema baseline was sealed at startup.
SCHEMA_PIN_REQUIRED=1

# Bind the gateway to loopback by default. Change deliberately.
GATEWAY_BIND=127.0.0.1

# Comma-separated list of origins allowed to call the gateway from a browser.
CORS_ALLOW_ORIGINS=http://localhost:8080
EOF

chmod 600 .env
echo "Wrote .env with freshly generated secrets (mode 600)."
echo "Export them into your shell for the test scripts with:  set -a; . ./.env; set +a"
