"""
Repeated-Deny Anomaly Detector — Behavioural Threat Intelligence for MCP
Scans existing audit NDJSON logs and flags any user/role that triggered 5+
DENY decisions within a 60-second sliding window.

Novel contribution: First application of sliding-window deny-burst detection
to MCP gateway audit logs. No published MCP paper applies behavioural anomaly
detection to access control audit trails.

Extends the gateway from enforcement → active threat intelligence.

Run: python3 tests/anomaly_detector.py
Input: logs/mcp_audit_*.ndjson (already generated by gateway)
Output: logs/anomaly_alerts.csv + console report
"""
import json
import csv
import time
from pathlib import Path
from collections import defaultdict


WINDOW_SECONDS = 60   # sliding window size
DENY_THRESHOLD = 5    # denies in window = alert
LOG_DIR = "logs"


def load_deny_events(log_dir: str) -> dict:
    """Load all DENY events from audit logs, keyed by user_id."""
    deny_events = defaultdict(list)   # user_id → [(timestamp, role, tool)]
    total_records = 0
    deny_count = 0

    for f in sorted(Path(log_dir).glob("mcp_audit_*.ndjson")):
        try:
            for line in f.read_text().splitlines():
                if not line.strip():
                    continue
                try:
                    r = json.loads(line)
                    total_records += 1
                    decision = r.get("policy_decision")
                    # Handle both string and boolean format
                    is_deny = (decision == "DENY" or decision is False)
                    if is_deny:
                        ts = r.get("timestamp_epoch") or r.get("timestamp", 0)
                        uid = r.get("user_id", "unknown")
                        role = r.get("role", "unknown")
                        tool = r.get("tool_name", "unknown")
                        deny_events[uid].append((float(ts), role, tool))
                        deny_count += 1
                except (json.JSONDecodeError, ValueError):
                    pass
        except Exception as e:
            pass

    print(f"  Loaded {total_records:,} audit records")
    print(f"  Found {deny_count:,} DENY events across {len(deny_events)} users")
    return deny_events


def detect_bursts(deny_events: dict) -> list:
    """Sliding-window burst detection: flag bursts of DENY >= THRESHOLD in WINDOW."""
    alerts = []

    for user_id, events in deny_events.items():
        # Sort by timestamp
        events_sorted = sorted(events, key=lambda x: x[0])
        timestamps = [e[0] for e in events_sorted]

        # Sliding window scan
        for i, ts in enumerate(timestamps):
            window_end = ts + WINDOW_SECONDS
            burst = [(t, r, tool) for t, r, tool in events_sorted
                     if ts <= t <= window_end]

            if len(burst) >= DENY_THRESHOLD:
                # Check we haven't already flagged this burst
                already_flagged = any(
                    a["user_id"] == user_id and abs(a["window_start"] - ts) < WINDOW_SECONDS
                    for a in alerts
                )
                if not already_flagged:
                    roles_seen = list(set(b[1] for b in burst))
                    tools_targeted = list(set(b[2] for b in burst))
                    alerts.append({
                        "user_id": user_id,
                        "role": roles_seen[0] if roles_seen else "unknown",
                        "burst_count": len(burst),
                        "window_start": ts,
                        "window_start_iso": time.strftime(
                            "%Y-%m-%dT%H:%M:%SZ", time.gmtime(ts)
                        ) if ts > 0 else "unknown",
                        "window_seconds": WINDOW_SECONDS,
                        "tools_targeted": ", ".join(tools_targeted[:5]),
                        "severity": "HIGH" if len(burst) >= DENY_THRESHOLD * 3 else "MEDIUM",
                    })
                break  # one alert per user per burst window

    return sorted(alerts, key=lambda x: x["burst_count"], reverse=True)


def run():
    print("\n" + "=" * 64)
    print("  MCP ANOMALY DETECTOR — Sliding-Window Deny-Burst Detection")
    print(f"  Threshold: {DENY_THRESHOLD}+ denies in {WINDOW_SECONDS}s window = ALERT")
    print("=" * 64)

    deny_events = load_deny_events(LOG_DIR)

    if not deny_events:
        print("  No DENY events found in audit logs.")
        return

    print(f"\n  Running burst detection (window={WINDOW_SECONDS}s, threshold={DENY_THRESHOLD})...")
    alerts = detect_bursts(deny_events)

    print(f"\n  {'User ID':<30} {'Role':<15} {'Burst':<7} {'At':<22} {'Severity':<8} Tools Targeted")
    print("  " + "-" * 90)

    if alerts:
        for a in alerts:
            print(f"  {a['user_id']:<30} {a['role']:<15} {a['burst_count']:<7} "
                  f"{a['window_start_iso']:<22} {a['severity']:<8} {a['tools_targeted']}")
    else:
        print("  No burst anomalies detected — no user exceeded the threshold.")
        print(f"  (This is the expected result for normal benchmark/test traffic)")

    print(f"\n  Total alerts: {len(alerts)}")

    # Save CSV
    ts_str = time.strftime("%Y%m%d_%H%M%S")
    out = f"{LOG_DIR}/anomaly_alerts_{ts_str}.csv"
    fieldnames = ["user_id", "role", "burst_count", "window_start_iso",
                  "window_seconds", "tools_targeted", "severity"]
    with open(out, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        for a in alerts:
            w.writerow({k: a.get(k, "") for k in fieldnames})

    print(f"  Saved: {out}")
    print(f"\n  Novel contribution: First sliding-window deny-burst detector")
    print(f"  applied to MCP gateway audit logs — active threat intelligence\n")
    return alerts


if __name__ == "__main__":
    run()
